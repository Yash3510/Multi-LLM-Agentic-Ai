// Icon generator for apps/web (ADR-0041 amendment: Phosphor, as the running app draws it).
// Source: src/lib/ui/icons/registry.json, our name -> a @phosphor-icons/core glyph and weight
// (regular unless the running app uses bold in that place). Writes src/lib/ui/icons/generated/
// icons.ts and contact-sheet.html, or exits 1 listing every problem and writing nothing. Paths
// resolve from this file, so it runs from any directory.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB = resolve(HERE, '../../apps/web');
const ICONS = join(WEB, 'src/lib/ui/icons');
const OUT = join(ICONS, 'generated');
const NOTICE = 'Generated by tools/icons — edit the generator, not this file.';
// Resolved like an import from apps/web, so a hoisted install is found too. The package exports
// only its SVGs, so the assets folder is found through one of them.
const PHOSPHOR = dirname(
  dirname(createRequire(join(WEB, 'package.json')).resolve('@phosphor-icons/core/regular/x.svg')),
);
// The package's own MIT licence, read at generation time so the notice always matches the
// installed version.
const LICENCE = join(dirname(PHOSPHOR), 'LICENSE');
const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const WEIGHTS = ['regular', 'bold'];

// Phosphor names a bold file "check-bold.svg"; regular files carry no suffix.
export const phosphorFile = (glyph, weight = 'regular') =>
  join(PHOSPHOR, weight, weight === 'regular' ? `${glyph}.svg` : `${glyph}-${weight}.svg`);

/** The single path inside one Phosphor file, drawn on its 256 grid. */
export function readPhosphor(text) {
  const svg = text.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/);
  if (!svg) throw new Error('not an svg');
  if (!/viewBox="0 0 256 256"/.test(svg[1])) throw new Error('not on the 256 grid');
  const tags = [...svg[2].matchAll(/<([a-z]+)\b([^>]*?)\/?>/gi)];
  const other = tags.find(([, tag]) => tag !== 'path');
  if (other) throw new Error(`<${other[1]}> is not a plain path`);
  if (tags.length !== 1) throw new Error('needs exactly one path');
  const attributes = [...tags[0][2].matchAll(/([\w-]+)="([^"]*)"/g)];
  const extra = attributes.filter(([, key]) => key !== 'd').map(([, key]) => key);
  if (extra.length) throw new Error(`<path> carries ${extra.join(', ')}`);
  const d = attributes.find(([, key]) => key === 'd')?.[2];
  if (!d) throw new Error('needs exactly one path');
  return d;
}

/** Every problem in the registry: names, entry shape, weights and missing glyphs. */
export function checkRegistry(registry, has) {
  const errors = [];
  for (const [name, entry] of Object.entries(registry)) {
    const weight = entry?.weight ?? 'regular';
    if (!NAME.test(name)) errors.push(`${name}: names are kebab-case`);
    else if (typeof entry?.phosphor !== 'string') errors.push(`${name}: needs a "phosphor" glyph name`);
    else if (!WEIGHTS.includes(weight)) errors.push(`${name}: weight is regular or bold`);
    else if (!has(entry.phosphor, weight))
      errors.push(`${name}: @phosphor-icons/core has no ${weight} glyph "${entry.phosphor}"`);
  }
  return errors;
}

export function build() {
  let registry;
  try {
    registry = JSON.parse(readFileSync(join(ICONS, 'registry.json'), 'utf8'));
  } catch (error) {
    return { errors: [`registry.json: ${error.message}`] };
  }
  const errors = checkRegistry(registry, (glyph, weight) =>
    existsSync(phosphorFile(glyph, weight)),
  ).map((message) => `registry.json: ${message}`);
  if (errors.length) return { errors };
  const icons = {};
  for (const [name, { phosphor, weight }] of Object.entries(registry)) {
    try {
      icons[name] = readPhosphor(readFileSync(phosphorFile(phosphor, weight), 'utf8'));
    } catch (error) {
      errors.push(`@phosphor-icons/core ${phosphor}: ${error.message}`);
    }
  }
  return errors.length ? { errors } : { errors, icons };
}

/** The licence as a legal comment: the bundler keeps a /*! … *\/ comment through minification, so
 * the notice ships in the built app beside the paths it covers. */
export function licenceComment(text) {
  const body = text.trim().replaceAll('*/', '* /').split('\n').map((line) => ` * ${line}`.trimEnd());
  return ['/*!', ' * @license Phosphor Icons (@phosphor-icons/core), MIT', ' *', ...body, ' */'].join('\n');
}

/** The module the components import: the licence, the path table and the name type. */
export function iconsModule(icons, licence = '') {
  const names = Object.keys(icons).map((name) => `'${name}'`).join(' | ');
  // The notice sits on the table itself: a comment above a type-only line is dropped with it.
  return `// ${NOTICE}
export type IconName = ${names};

${licence ? `${licenceComment(licence)}\n` : ''}export const ICONS: Readonly<Record<IconName, string>> = ${JSON.stringify(icons, null, 2)};
`;
}

const drawn = (d, size) =>
  `<svg width="${size}" height="${size}" viewBox="0 0 256 256" fill="currentColor"><path d="${d}"/></svg>`;

/** Every registered glyph at 16, 18 and 24 px, for review. */
export function contactSheet(icons) {
  const rows = Object.entries(icons).map(
    ([name, d]) => `<tr><th>${name}</th>${[16, 18, 24].map((s) => `<td>${drawn(d, s)}</td>`).join('')}</tr>`,
  );
  return `<!doctype html>
<!-- ${NOTICE} -->
<meta charset="utf-8" />
<title>Icon contact sheet</title>
<style>
  :root { color-scheme: light dark; font: 13px/1.5 system-ui, sans-serif; }
  body { margin: 24px; background: Canvas; color: CanvasText; }
  th, td { padding: 6px 12px; text-align: left; font-weight: 400; }
  td svg { display: block; }
</style>
<table>
${rows.join('\n')}
</table>
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { errors, icons } = build();
  if (errors.length) {
    for (const error of errors) console.error(`icons: ${error}`);
    console.error(`icons: ${errors.length} problem${errors.length === 1 ? '' : 's'}; nothing was written`);
    process.exit(1);
  }
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, 'icons.ts'), iconsModule(icons, readFileSync(LICENCE, 'utf8')));
  writeFileSync(join(OUT, 'contact-sheet.html'), contactSheet(icons));
  console.log(`icons: ${Object.keys(icons).length} Phosphor glyphs -> ${relative(process.cwd(), OUT)}`);
}
