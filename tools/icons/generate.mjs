// Icon generator for apps/web (ADR-0041 amendment: Lucide replaces Phosphor and the signature set).
// Source: src/lib/ui/icons/registry.json, our name -> a lucide-static glyph. Writes
// src/lib/ui/icons/generated/icons.ts and contact-sheet.html, or exits 1 listing every problem and
// writing nothing. Paths resolve from this file, so it runs from any directory.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB = resolve(HERE, '../../apps/web');
const ICONS = join(WEB, 'src/lib/ui/icons');
const OUT = join(ICONS, 'generated');
const NOTICE = 'Generated by tools/icons — edit the generator, not this file.';
// Resolved like an import from apps/web, so a hoisted install is found too.
const LUCIDE_ICONS = join(
  dirname(createRequire(join(WEB, 'package.json')).resolve('lucide-static/package.json')),
  'icons',
);
const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
// The shapes Lucide draws with, and the geometry each may carry. Anything else is refused.
const SHAPES = {
  path: ['d'],
  circle: ['cx', 'cy', 'r'],
  ellipse: ['cx', 'cy', 'rx', 'ry'],
  line: ['x1', 'y1', 'x2', 'y2'],
  polyline: ['points'],
  polygon: ['points'],
  rect: ['x', 'y', 'width', 'height', 'rx', 'ry'],
};

export const lucideFile = (glyph) => join(LUCIDE_ICONS, `${glyph}.svg`);

/** The shapes inside one lucide-static file, as [tag, geometry] pairs. */
export function readLucide(text) {
  const inner = text.replace(/<!--[\s\S]*?-->/g, '').match(/<svg\b[^>]*>([\s\S]*)<\/svg>/);
  if (!inner) throw new Error('not an svg');
  const parts = [];
  for (const [, tag, body] of inner[1].matchAll(/<([a-z]+)\b([^>]*?)\/?>/gi)) {
    if (!SHAPES[tag]) throw new Error(`<${tag}> is not a plain shape`);
    const attributes = Object.fromEntries(
      [...body.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]),
    );
    const extra = Object.keys(attributes).filter((key) => !SHAPES[tag].includes(key));
    if (extra.length) throw new Error(`<${tag}> carries ${extra.join(', ')}`);
    parts.push([tag, attributes]);
  }
  if (!parts.length) throw new Error('no shapes');
  return parts;
}

/** Every problem in the registry: names, entry shape and missing glyphs. */
export function checkRegistry(registry, has) {
  const errors = [];
  for (const [name, entry] of Object.entries(registry)) {
    if (!NAME.test(name)) errors.push(`${name}: names are kebab-case`);
    else if (typeof entry?.lucide !== 'string') errors.push(`${name}: needs a "lucide" glyph name`);
    else if (!has(entry.lucide)) errors.push(`${name}: lucide-static has no glyph "${entry.lucide}"`);
  }
  return errors;
}

export function build() {
  let registry;
  try {
    registry = JSON.parse(readFileSync(join(ICONS, 'registry.json'), 'utf8'));
  } catch (error) {
    return { errors: [`registry.json: ${error.message}`] };
  }
  const errors = checkRegistry(registry, (glyph) => existsSync(lucideFile(glyph))).map(
    (message) => `registry.json: ${message}`,
  );
  if (errors.length) return { errors };
  const icons = {};
  for (const [name, { lucide }] of Object.entries(registry)) {
    try {
      icons[name] = readLucide(readFileSync(lucideFile(lucide), 'utf8'));
    } catch (error) {
      errors.push(`lucide-static ${lucide}: ${error.message}`);
    }
  }
  return errors.length ? { errors } : { errors, icons };
}

/** The module the components import: the shape table and the name type. */
export function iconsModule(icons) {
  const names = Object.keys(icons).map((name) => `'${name}'`).join(' | ');
  return `// ${NOTICE}
export type IconName = ${names};

export type IconPart = readonly [tag: string, geometry: Readonly<Record<string, string>>];

export const ICONS: Readonly<Record<IconName, readonly IconPart[]>> = ${JSON.stringify(icons, null, 2)};
`;
}

const drawn = (parts, size) =>
  `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
  `stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">` +
  parts
    .map(([tag, geometry]) => `<${tag} ${Object.entries(geometry).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`)
    .join('') +
  '</svg>';

/** Every registered glyph at 16, 20 and 24 px, for review. */
export function contactSheet(icons) {
  const rows = Object.entries(icons).map(
    ([name, parts]) => `<tr><th>${name}</th>${[16, 20, 24].map((s) => `<td>${drawn(parts, s)}</td>`).join('')}</tr>`,
  );
  return `<!doctype html>
<!-- ${NOTICE} -->
<meta charset="utf-8" />
<title>Icon contact sheet</title>
<style>
  :root { color-scheme: light dark; font: 13px/1.5 system-ui, sans-serif; }
  body { margin: 24px; background: Canvas; color: CanvasText; }
  th, td { padding: 6px 12px; text-align: left; font-weight: 400; }
  td svg { display: block; }
</style>
<table>
${rows.join('\n')}
</table>
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { errors, icons } = build();
  if (errors.length) {
    for (const error of errors) console.error(`icons: ${error}`);
    console.error(`icons: ${errors.length} problem${errors.length === 1 ? '' : 's'}; nothing was written`);
    process.exit(1);
  }
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, 'icons.ts'), iconsModule(icons));
  writeFileSync(join(OUT, 'contact-sheet.html'), contactSheet(icons));
  console.log(`icons: ${Object.keys(icons).length} Lucide glyphs -> ${relative(process.cwd(), OUT)}`);
}
